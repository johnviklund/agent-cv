import { copyFile, mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { loadOwner } from "./owner.mjs";
import { writeComparisonEvidence } from "./build-comparison-evidence.mjs";
import { writeComparisonContract } from "./build-comparison-contract.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const publicFiles = ["cv.md", "projects.md", "overview.md", "repositories.md"];
const workerFiles = ["meta.md", "cv.md", "overview.md", "experience.md", "projects.md", "repositories.md", "skills.md", "personal.md", "interests.md", "faq.md"];

// The Worker gets identity, site, links, contact and the site's updatedAt; deploy settings and analytics stay build-only.
export async function writeOwnerModule({ root, owner, site }) {
  const { deploy, analytics, ...publicOwner } = owner;
  await mkdir(resolve(root, "src", "data"), { recursive: true });
  await writeFile(
    resolve(root, "src", "data", "owner.js"),
    `// Generated by npm run sync:data from owner.json.\nexport default ${JSON.stringify(publicOwner, null, 2)};\nexport const updatedAt = ${JSON.stringify(site.updatedAt)};\n`,
  );
}

async function main() {
  await mkdir(resolve(root, "public"), { recursive: true });
  await mkdir(resolve(root, "src", "data"), { recursive: true });
  await Promise.all([
    copyFile(resolve(root, "tokens.css"), resolve(root, "public", "tokens.css")),
    ...publicFiles.map((file) => copyFile(
      resolve(root, "data", file),
      resolve(root, "public", file),
    )),
    ...workerFiles.map((file) => copyFile(
      resolve(root, "data", file),
      resolve(root, "src", "data", file),
    )),
  ]);

  const [comparisonEvidence, comparisonContract] = await Promise.all([
    writeComparisonEvidence({ root }),
    writeComparisonContract({ repositoryRoot: root }),
  ]);

  console.log(`Synced ${publicFiles.length} public and ${workerFiles.length} Worker Markdown resources, ${comparisonEvidence.items.length} comparison evidence items, and comparison contract v${comparisonContract.schemaVersion}.`);
  const { owner, site } = await loadOwner();
  await writeOwnerModule({ root, owner, site });
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
