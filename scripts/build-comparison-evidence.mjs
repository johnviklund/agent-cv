import { createHash } from "node:crypto";
import { mkdir, readFile, realpath, rename, writeFile } from "node:fs/promises";
import { dirname, relative, resolve, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const PRIMARY_SOURCE_PATHS = new Set([
  "data/cv.md",
  "data/overview.md",
  "data/projects.md",
]);
const REPOSITORY_SOURCE_PATH = "data/repositories.md";
const MAX_ITEMS = 48;
const MAX_OUTPUT_BYTES = 64 * 1024;
const ID_PATTERN = /^[a-z0-9]+(?:[.-][a-z0-9]+)*$/;
const MARKDOWN_HTML_PATTERN = /<!--|<\/?[a-z][^>]*>/i;
const SENSITIVE_PATTERNS = [
  /\b[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}\b/i,
  /\b(?:sk|ghp|github_pat)_[A-Za-z0-9_-]{12,}\b/,
  /\bprivateNotes\b/i,
  /(?:^|\s)\.dev\.vars(?:\s|$)/i,
  /BEGIN\s+PRIVATE/i,
  /\bapi[_ -]?key\s*[:=]\s*\S+/i,
];

export async function buildComparisonEvidenceCatalog({ root, manifest }) {
  const validated = validateManifest(manifest);
  const sourceCache = new Map();
  const items = [];

  for (const entry of validated.items) {
    const markdown = await readSource(root, entry.source.path, sourceCache);
    const selected = selectSection(markdown, entry.source, entry.id);
    assertSafeEvidence(selected.text, `${entry.id} primary evidence`);

    const item = {
      id: entry.id,
      title: selected.title,
      text: selected.text,
      source: entry.source,
    };

    if (entry.supportingSources.length) {
      item.supportingSources = [];
      for (const source of entry.supportingSources) {
        const repositoryMarkdown = await readSource(root, source.path, sourceCache);
        const section = selectSection(repositoryMarkdown, source, `${entry.id} repository support`);
        const repositoryIntro = section.text.split(/^#{2,6}\s+/m, 1)[0].trim();
        assertSafeEvidence(repositoryIntro, `${entry.id} repository support`);
        const urls = [...repositoryIntro.matchAll(/^- Repository:\s*(\S+)\s*$/gm)]
          .map((match) => normalizeSafeUrl(match[1], `${entry.id} repository support`));
        if (urls.length !== 1) {
          throw new Error(`${entry.id} repository support must resolve to exactly one Repository link.`);
        }
        item.supportingSources.push({
          trust: "untrusted-secondary",
          url: urls[0],
          source,
        });
      }
    }

    items.push(item);
  }

  const digestInput = JSON.stringify({ schemaVersion: 1, items });
  const digest = `sha256:${createHash("sha256").update(digestInput).digest("hex")}`;
  const catalog = { schemaVersion: 1, digest, items };
  const output = `${JSON.stringify(catalog, null, 2)}\n`;
  if (Buffer.byteLength(output, "utf8") > MAX_OUTPUT_BYTES) {
    throw new Error("Comparison evidence output must not exceed 64 KiB.");
  }
  return catalog;
}

export async function writeComparisonEvidence({ root, manifestPath } = {}) {
  const repositoryRoot = resolve(root || dirname(fileURLToPath(import.meta.url)), root ? "." : "..");
  const configPath = resolve(repositoryRoot, manifestPath || "config/comparison-evidence.json");
  const manifest = JSON.parse(await readFile(configPath, "utf8"));
  const catalog = await buildComparisonEvidenceCatalog({ root: repositoryRoot, manifest });
  const json = `${JSON.stringify(catalog, null, 2)}\n`;
  const workerModule = `// Generated by scripts/build-comparison-evidence.mjs. Do not edit.\nexport default ${json.trim()};\n`;
  const publicPath = resolve(repositoryRoot, "public/evidence.json");
  const workerPath = resolve(repositoryRoot, "src/data/comparison-evidence.js");

  await Promise.all([
    mkdir(dirname(publicPath), { recursive: true }),
    mkdir(dirname(workerPath), { recursive: true }),
  ]);
  await Promise.all([
    writeAtomically(publicPath, json),
    writeAtomically(workerPath, workerModule),
  ]);
  return catalog;
}

export function validateManifest(value) {
  assertExactKeys(value, ["schemaVersion", "items"], "Comparison evidence manifest");
  if (value.schemaVersion !== 1) {
    throw new Error("Comparison evidence manifest requires schemaVersion 1.");
  }
  if (!Array.isArray(value.items) || value.items.length > MAX_ITEMS) {
    throw new Error(`Comparison evidence manifest must contain at most ${MAX_ITEMS} items.`);
  }

  const seenIds = new Set();
  return {
    schemaVersion: 1,
    items: value.items.map((entry, index) => {
      assertExactKeys(entry, ["id", "source", "supportingSources"], `Evidence item ${index + 1}`, ["supportingSources"]);
      const id = typeof entry.id === "string" ? entry.id.trim() : "";
      if (!ID_PATTERN.test(id) || id.length > 100) {
        throw new Error(`Evidence item ${index + 1} has an invalid stable ID.`);
      }
      if (seenIds.has(id)) throw new Error(`Duplicate evidence ID: ${id}`);
      seenIds.add(id);

      const source = validateSelector(entry.source, `Evidence item ${id}`);
      if (source.path === REPOSITORY_SOURCE_PATH) {
        throw new Error(`${id}: repository evidence cannot be primary.`);
      }
      if (!PRIMARY_SOURCE_PATHS.has(source.path)) {
        throw new Error(`${id}: primary evidence must use an approved public source.`);
      }

      const supportingSources = entry.supportingSources === undefined ? [] : entry.supportingSources;
      if (!Array.isArray(supportingSources) || supportingSources.length > 3) {
        throw new Error(`${id}: supportingSources must contain at most 3 selectors.`);
      }
      return {
        id,
        source,
        supportingSources: supportingSources.map((support, supportIndex) => {
          const validatedSupport = validateSelector(support, `${id} support ${supportIndex + 1}`);
          if (validatedSupport.path !== REPOSITORY_SOURCE_PATH) {
            throw new Error(`${id}: repository support source must use ${REPOSITORY_SOURCE_PATH}.`);
          }
          return validatedSupport;
        }),
      };
    }),
  };
}

function validateSelector(value, label) {
  assertExactKeys(value, ["path", "headingPath"], `${label} selector`);
  const path = typeof value.path === "string" ? value.path.trim() : "";
  if (!PRIMARY_SOURCE_PATHS.has(path) && path !== REPOSITORY_SOURCE_PATH) {
    throw new Error(`${label} selector path is not an approved public source and may contain traversal.`);
  }
  if (!Array.isArray(value.headingPath) || value.headingPath.length < 1 || value.headingPath.length > 5) {
    throw new Error(`${label} requires a headingPath with 1 to 5 headings.`);
  }
  const headingPath = value.headingPath.map((heading) => {
    const clean = typeof heading === "string" ? normalizeInline(heading) : "";
    if (!clean || clean.length > 160 || clean === "." || clean === ".." || clean.includes("\\") || /(?:^|\/)\.\.(?:\/|$)/.test(clean)) {
      throw new Error(`${label} has an unsafe heading selector.`);
    }
    return clean;
  });
  return { path, headingPath };
}

function selectSection(markdown, selector, label) {
  const normalized = normalizeMarkdown(markdown);
  const lines = normalized.split("\n");
  const headings = [];
  const hierarchy = [];

  for (let index = 0; index < lines.length; index += 1) {
    const match = lines[index].match(/^(#{1,6})[ \t]+(.+?)[ \t]*#*[ \t]*$/);
    if (!match) continue;
    const level = match[1].length;
    const title = normalizeInline(match[2]);
    hierarchy[level] = title;
    hierarchy.length = level + 1;
    if (level === 1) continue;
    headings.push({
      index,
      level,
      title,
      headingPath: hierarchy.slice(2, level + 1).filter(Boolean),
    });
  }

  const matches = headings.filter(({ headingPath }) => arraysEqual(headingPath, selector.headingPath));
  if (matches.length === 0) {
    throw new Error(`${label}: missing heading ${selector.headingPath.join(" > ")} in ${selector.path}.`);
  }
  if (matches.length > 1) {
    throw new Error(`${label}: ambiguous heading ${selector.headingPath.join(" > ")} in ${selector.path}.`);
  }

  const selected = matches[0];
  const next = headings.find((heading) => heading.index > selected.index && heading.level <= selected.level);
  const body = normalizeMarkdown(lines.slice(selected.index + 1, next?.index ?? lines.length).join("\n"));
  if (!body) throw new Error(`${label}: selected evidence is empty.`);
  return { title: selected.title, text: body };
}

async function readSource(root, sourcePath, cache) {
  if (cache.has(sourcePath)) return cache.get(sourcePath);
  const repositoryRoot = await realpath(resolve(root));
  const requested = resolve(repositoryRoot, sourcePath);
  let canonical;
  try {
    canonical = await realpath(requested);
  } catch {
    throw new Error(`Missing approved evidence source: ${sourcePath}.`);
  }
  const pathFromRoot = relative(repositoryRoot, canonical);
  if (pathFromRoot === ".." || pathFromRoot.startsWith(`..${sep}`) || resolve(canonical) === repositoryRoot) {
    throw new Error(`Evidence source traversal is not allowed: ${sourcePath}.`);
  }
  const value = await readFile(canonical, "utf8");
  cache.set(sourcePath, value);
  return value;
}

function assertSafeEvidence(text, label) {
  if (/[^\t\n\r\x20-\x7e\u00a0-\uffff]/u.test(text)) {
    throw new Error(`${label} contains unsafe control characters.`);
  }
  if (MARKDOWN_HTML_PATTERN.test(text)) {
    throw new Error(`${label} contains Markdown HTML.`);
  }
  if (SENSITIVE_PATTERNS.some((pattern) => pattern.test(text))) {
    throw new Error(`${label} contains a sensitive string.`);
  }
  for (const match of text.matchAll(/!?\[[^\]]*\]\(\s*([^\s)]+)/g)) {
    normalizeSafeUrl(match[1], label);
  }
}

function normalizeSafeUrl(value, label) {
  let decoded;
  try {
    decoded = decodeURIComponent(String(value).replace(/[\u0000-\u0020\u007f]/g, ""));
  } catch {
    throw new Error(`${label} contains an unsafe link.`);
  }
  let parsed;
  try {
    parsed = new URL(decoded);
  } catch {
    throw new Error(`${label} contains an unsafe link.`);
  }
  if (parsed.protocol !== "https:" && parsed.protocol !== "http:") {
    throw new Error(`${label} contains an unsafe link.`);
  }
  return parsed.href;
}

function normalizeMarkdown(value) {
  return String(value)
    .replace(/\r\n?/g, "\n")
    .split("\n")
    .map((line) => line.replace(/[ \t]+$/g, ""))
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

function normalizeInline(value) {
  return String(value).replace(/[\u0000-\u001f\u007f]/g, " ").replace(/\s+/g, " ").trim();
}

function arraysEqual(left, right) {
  return left.length === right.length && left.every((value, index) => value === right[index]);
}

function assertExactKeys(value, allowed, label, optional = []) {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    throw new Error(`${label} must be an object.`);
  }
  const allowedSet = new Set(allowed);
  const extras = Object.keys(value).filter((key) => !allowedSet.has(key));
  if (extras.length) throw new Error(`${label} contains unsupported fields: ${extras.join(", ")}.`);
  for (const key of allowed) {
    if (!optional.includes(key) && !(key in value)) throw new Error(`${label} requires ${key}.`);
  }
}

async function writeAtomically(path, content) {
  const temporary = `${path}.tmp-${process.pid}`;
  await writeFile(temporary, content);
  await rename(temporary, path);
}

const isCli = process.argv[1]
  && pathToFileURL(resolve(process.argv[1])).href === import.meta.url;
if (isCli) {
  const catalog = await writeComparisonEvidence();
  console.log(`Built ${catalog.items.length} comparison evidence items (${catalog.digest}).`);
}
