import { mkdir, readFile, rename, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export async function writeComparisonContract({ repositoryRoot = root } = {}) {
  const configPath = resolve(repositoryRoot, "config/comparison-contract.json");
  const contract = validateContract(JSON.parse(await readFile(configPath, "utf8")));
  const moduleSource = generatedModule(contract);
  const workerPath = resolve(repositoryRoot, "src/data/comparison-contract.js");
  const publicPath = resolve(repositoryRoot, "public/comparison-contract.js");
  await Promise.all([mkdir(dirname(workerPath), { recursive: true }), mkdir(dirname(publicPath), { recursive: true })]);
  await Promise.all([writeAtomically(workerPath, moduleSource), writeAtomically(publicPath, moduleSource)]);
  return contract;
}

export function validateContract(value) {
  assertExactKeys(value, ["schemaVersion", "limits", "coverageStates", "reasonCodes", "identity", "ordering", "cardinality"], "Comparison contract");
  if (value.schemaVersion !== 2) throw new Error("Comparison contract requires schemaVersion 2.");
  assertExactKeys(value.limits, [
    "maxBodyBytes", "minRoles", "maxRoles", "maxTitleCharacters", "maxCompanyCharacters",
    "maxDescriptionCharacters", "maxCombinedRoleCharacters", "maxRows", "maxRequirementsPerRole",
    "maxSourceRequirementsPerRole", "maxUnmappedRequirementsPerRole",
    "maxRowLabelCharacters", "maxRequirementCharacters", "maxEvidencePerCell", "maxQuestionsPerCell",
    "maxQuestionCharacters", "maxProviderResponseBytes",
  ], "Comparison limits");
  for (const [name, limit] of Object.entries(value.limits)) {
    if (!Number.isSafeInteger(limit) || limit < 1) throw new Error(`Comparison limit ${name} must be a positive integer.`);
  }
  if (value.limits.minRoles !== 1 || value.limits.maxRoles !== 3 || value.limits.maxRows !== 24
    || value.limits.maxRequirementsPerRole !== 16 || value.limits.maxSourceRequirementsPerRole !== 96
    || value.limits.maxUnmappedRequirementsPerRole !== 96) {
    throw new Error("Comparison cardinality is fixed at 1–3 roles, 24 rows, 16 assessed requirements, and 96 source or unmapped requirements per role.");
  }
  if (JSON.stringify(value.coverageStates) !== JSON.stringify(["documented", "transferable", "not_documented", "not_listed"])) {
    throw new Error("Comparison coverage states are fixed and ordered.");
  }
  assertExactKeys(value.reasonCodes, ["documented", "transferable"], "Comparison reason codes");
  for (const [coverage, codes] of Object.entries(value.reasonCodes)) {
    if (!Array.isArray(codes) || !codes.length || new Set(codes).size !== codes.length || codes.some((code) => !/^[a-z]+(?:_[a-z]+)*$/.test(code))) {
      throw new Error(`Comparison ${coverage} reason codes must be unique snake-case values.`);
    }
  }
  assertStringMap(value.identity, ["role", "row", "cell"], "Comparison identity");
  assertStringMap(value.ordering, ["roles", "rows", "cells", "unmappedRequirements"], "Comparison ordering");
  assertStringMap(value.cardinality, ["roles", "rows", "cells", "listedRequirements", "unmappedRequirements"], "Comparison cardinality");
  return value;
}

